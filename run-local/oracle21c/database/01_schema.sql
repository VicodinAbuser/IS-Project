-- =====================================================================
-- Users and access control
-- =====================================================================
CREATE TABLE users (
  user_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name          VARCHAR2(100) NOT NULL,
  email              VARCHAR2(255) NOT NULL CONSTRAINT uq_users_email UNIQUE
                     CONSTRAINT ck_users_email_lower CHECK (email = LOWER(email)),
  password_hash      VARCHAR2(255) NOT NULL,
  account_status     VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL
                     CONSTRAINT ck_users_status CHECK (account_status IN ('ACTIVE', 'DISABLED')),
  failed_login_count NUMBER(3)     DEFAULT 0 NOT NULL CONSTRAINT ck_users_failed CHECK (failed_login_count >= 0),
  locked_until       TIMESTAMP,
  last_login_at      TIMESTAMP,
  created_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_users_updated ON users (updated_at);
COMMENT ON TABLE  users IS 'Login accounts for everyone: customers and staff. What a user may do comes from USER_PROFILES.';
COMMENT ON COLUMN users.user_id IS 'Unique number of the user';
COMMENT ON COLUMN users.full_name IS 'Name shown in the app and on orders';
COMMENT ON COLUMN users.email IS 'Login name (username). Stored in lower case, unique';
COMMENT ON COLUMN users.password_hash IS 'bcrypt hash of the password. The real password is never stored';
COMMENT ON COLUMN users.account_status IS 'ACTIVE = can log in, DISABLED = blocked by an administrator';
COMMENT ON COLUMN users.failed_login_count IS 'Wrong passwords in a row; reset after a successful login';
COMMENT ON COLUMN users.locked_until IS 'After too many wrong passwords, logins are refused until this time';
COMMENT ON COLUMN users.last_login_at IS 'Time of the last successful login';
COMMENT ON COLUMN users.created_at IS 'When the account was created';
COMMENT ON COLUMN users.updated_at IS 'Last change to this row (set by trigger TRG_USERS_UPDATED)';

CREATE TABLE outlets (
  outlet_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      VARCHAR2(100) NOT NULL CONSTRAINT uq_outlets_name UNIQUE,
  city      VARCHAR2(100) NOT NULL,
  address   VARCHAR2(500)
);
COMMENT ON TABLE  outlets IS 'Stores and warehouses. Stock is kept per outlet, and every order is served by one outlet';
COMMENT ON COLUMN outlets.name IS 'Outlet name, e.g. Mumbai Central';
COMMENT ON COLUMN outlets.city IS 'City the outlet is in';
COMMENT ON COLUMN outlets.address IS 'Area / street address of the outlet';

CREATE TABLE customer_profiles (
  customer_id         NUMBER PRIMARY KEY
                      CONSTRAINT fk_custprof_user REFERENCES users (user_id) ON DELETE CASCADE,
  phone               VARCHAR2(20) CONSTRAINT uq_custprof_phone UNIQUE,
  address_line        VARCHAR2(300),
  city                VARCHAR2(100),
  state               VARCHAR2(100),
  pincode             VARCHAR2(10) CONSTRAINT ck_custprof_pincode CHECK (REGEXP_LIKE(pincode, '^[0-9]{6}$')),
  preferred_outlet_id NUMBER CONSTRAINT fk_custprof_outlet REFERENCES outlets (outlet_id) ON DELETE SET NULL,
  created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_custprof_outlet ON customer_profiles (preferred_outlet_id);
CREATE INDEX ix_custprof_city ON customer_profiles (city);
COMMENT ON TABLE  customer_profiles IS 'Personal details of a customer. One row per customer, same ID as USERS.USER_ID';
COMMENT ON COLUMN customer_profiles.customer_id IS 'The customer = USERS.USER_ID';
COMMENT ON COLUMN customer_profiles.phone IS 'Mobile number (unique)';
COMMENT ON COLUMN customer_profiles.address_line IS 'House / street / area of the default delivery address';
COMMENT ON COLUMN customer_profiles.city IS 'City of the default delivery address';
COMMENT ON COLUMN customer_profiles.state IS 'State of the default delivery address';
COMMENT ON COLUMN customer_profiles.pincode IS '6-digit PIN code';
COMMENT ON COLUMN customer_profiles.preferred_outlet_id IS 'Outlet the shop opens with for this customer';

CREATE TABLE profiles (
  profile_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_code VARCHAR2(30)  NOT NULL CONSTRAINT uq_profiles_code UNIQUE,
  profile_name VARCHAR2(100) NOT NULL,
  description  VARCHAR2(500),
  is_staff     NUMBER(1) DEFAULT 0 NOT NULL CONSTRAINT ck_profiles_staff CHECK (is_staff IN (0, 1))
);
COMMENT ON TABLE  profiles IS 'Kinds of user (roles). A user can have one or more profiles (USER_PROFILES)';
COMMENT ON COLUMN profiles.profile_code IS 'Code used by the application, e.g. STORE_MANAGER';
COMMENT ON COLUMN profiles.is_staff IS '1 = employee profile (opens the admin pages), 0 = customer';

CREATE TABLE permissions (
  permission_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  permission_code VARCHAR2(30)  NOT NULL CONSTRAINT uq_permissions_code UNIQUE,
  permission_name VARCHAR2(100) NOT NULL,
  module          VARCHAR2(20)  NOT NULL
                  CONSTRAINT ck_permissions_module CHECK (module IN ('CATALOG', 'ORDERS', 'INVENTORY', 'REPORTS', 'USERS')),
  access_type     VARCHAR2(10)  NOT NULL
                  CONSTRAINT ck_permissions_access CHECK (access_type IN ('READ', 'WRITE', 'REPORT', 'DOWNLOAD', 'ADMIN')),
  description     VARCHAR2(500)
);
COMMENT ON TABLE  permissions IS 'Single rights that the Python API checks before doing something';
COMMENT ON COLUMN permissions.permission_code IS 'Code used by the application, e.g. STOCK_WRITE';
COMMENT ON COLUMN permissions.module IS 'Part of the system the right belongs to';
COMMENT ON COLUMN permissions.access_type IS 'READ = view, WRITE = change, REPORT = see reports, DOWNLOAD = export files, ADMIN = manage users';

CREATE TABLE authorizations (
  profile_id    NUMBER NOT NULL CONSTRAINT fk_auth_profile REFERENCES profiles (profile_id) ON DELETE CASCADE,
  permission_id NUMBER NOT NULL CONSTRAINT fk_auth_permission REFERENCES permissions (permission_id) ON DELETE CASCADE,
  granted_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  granted_by    NUMBER CONSTRAINT fk_auth_granted_by REFERENCES users (user_id) ON DELETE SET NULL,
  CONSTRAINT pk_authorizations PRIMARY KEY (profile_id, permission_id)
);
CREATE INDEX ix_auth_permission ON authorizations (permission_id);
COMMENT ON TABLE  authorizations IS 'Which profile has which permission (many-to-many PROFILES x PERMISSIONS)';
COMMENT ON COLUMN authorizations.granted_by IS 'User who granted it; NULL = part of the standard setup';

CREATE TABLE user_profiles (
  user_id     NUMBER NOT NULL CONSTRAINT fk_userprof_user REFERENCES users (user_id) ON DELETE CASCADE,
  profile_id  NUMBER NOT NULL CONSTRAINT fk_userprof_profile REFERENCES profiles (profile_id),
  assigned_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  assigned_by NUMBER CONSTRAINT fk_userprof_assigned_by REFERENCES users (user_id) ON DELETE SET NULL,
  CONSTRAINT pk_user_profiles PRIMARY KEY (user_id, profile_id)
);
CREATE INDEX ix_userprof_profile ON user_profiles (profile_id);
COMMENT ON TABLE  user_profiles IS 'Which user has which profile (many-to-many USERS x PROFILES)';
COMMENT ON COLUMN user_profiles.assigned_by IS 'Administrator who assigned it; NULL = self sign-up or standard setup';

-- =====================================================================
-- Catalogue
-- =====================================================================
CREATE TABLE categories (
  category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(100) NOT NULL CONSTRAINT uq_categories_name UNIQUE
);
COMMENT ON TABLE categories IS 'Product groups, e.g. Electronics, Books';

CREATE TABLE suppliers (
  supplier_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(150) NOT NULL CONSTRAINT uq_suppliers_name UNIQUE,
  contact_email VARCHAR2(255),
  phone         VARCHAR2(20)
);
COMMENT ON TABLE suppliers IS 'Companies we buy stock from';

CREATE TABLE products (
  product_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku           VARCHAR2(50)  NOT NULL CONSTRAINT uq_products_sku UNIQUE,
  name          VARCHAR2(150) NOT NULL,
  description   VARCHAR2(1000),
  price         NUMBER(10,2)  NOT NULL CONSTRAINT ck_products_price CHECK (price >= 0),
  image_url     VARCHAR2(500),
  reorder_level NUMBER(6)     DEFAULT 10 NOT NULL CONSTRAINT ck_products_reorder CHECK (reorder_level >= 0),
  is_active     NUMBER(1)     DEFAULT 1 NOT NULL CONSTRAINT ck_products_active CHECK (is_active IN (0, 1)),
  category_id   NUMBER CONSTRAINT fk_products_category REFERENCES categories (category_id),
  supplier_id   NUMBER CONSTRAINT fk_products_supplier REFERENCES suppliers (supplier_id),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_products_name ON products (name);
CREATE INDEX ix_products_updated ON products (updated_at);
COMMENT ON TABLE  products IS 'The catalogue, shared by all outlets. Stock per outlet is in INVENTORY';
COMMENT ON COLUMN products.sku IS 'Stock keeping unit: the product code, unique';
COMMENT ON COLUMN products.price IS 'Current selling price in rupees';
COMMENT ON COLUMN products.reorder_level IS 'Stock at or below this level counts as low stock';
COMMENT ON COLUMN products.is_active IS '1 = on sale, 0 = hidden from the shop (old orders keep it)';

-- =====================================================================
-- Stock: one row per product per outlet
-- =====================================================================
CREATE TABLE inventory (
  inventory_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id   NUMBER NOT NULL CONSTRAINT fk_inventory_product REFERENCES products (product_id) ON DELETE CASCADE,
  outlet_id    NUMBER NOT NULL CONSTRAINT fk_inventory_outlet  REFERENCES outlets (outlet_id)  ON DELETE CASCADE,
  quantity     NUMBER(10) DEFAULT 0 NOT NULL CONSTRAINT ck_inventory_qty CHECK (quantity >= 0),  -- can never go negative
  updated_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_inventory_product_outlet UNIQUE (product_id, outlet_id)
);
CREATE INDEX ix_inventory_outlet ON inventory (outlet_id);
CREATE INDEX ix_inventory_updated ON inventory (updated_at);
COMMENT ON TABLE  inventory IS 'Units of each product on the shelf at each outlet. Every change is logged in STOCK_MOVEMENTS';
COMMENT ON COLUMN inventory.quantity IS 'Units in stock now; the CHECK constraint stops it going below 0';
COMMENT ON COLUMN inventory.updated_at IS 'Time of the last stock change';

-- =====================================================================
-- Orders
-- =====================================================================
CREATE TABLE orders (
  order_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id      NUMBER NOT NULL CONSTRAINT fk_orders_customer REFERENCES users (user_id),
  outlet_id        NUMBER NOT NULL CONSTRAINT fk_orders_outlet REFERENCES outlets (outlet_id),
  order_status     VARCHAR2(20) DEFAULT 'PENDING_PAYMENT' NOT NULL
                   CONSTRAINT ck_orders_status CHECK (order_status IN ('PENDING_PAYMENT', 'PAID', 'CANCELLED', 'RETURNED')),
  total_amount     NUMBER(12,2) DEFAULT 0 NOT NULL CONSTRAINT ck_orders_total CHECK (total_amount >= 0),
  shipping_address VARCHAR2(500) NOT NULL,
  created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_orders_created_status ON orders (created_at, order_status);   -- quarterly reports
CREATE INDEX ix_orders_customer ON orders (customer_id);
CREATE INDEX ix_orders_updated ON orders (updated_at);
COMMENT ON TABLE  orders IS 'One row per order. Customer name: join USERS, or use view V_ORDER_DETAILS';
COMMENT ON COLUMN orders.customer_id IS 'Who placed the order (USERS.USER_ID)';
COMMENT ON COLUMN orders.outlet_id IS 'Outlet whose stock the order is served from';
COMMENT ON COLUMN orders.order_status IS 'PENDING_PAYMENT -> PAID; or CANCELLED (before shipping) / RETURNED (after shipping)';
COMMENT ON COLUMN orders.total_amount IS 'Sum of quantity x unit price of its ORDER_ITEMS';
COMMENT ON COLUMN orders.updated_at IS 'Last change to the order, its payment or its delivery (kept up to date by triggers)';

CREATE TABLE order_items (
  order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      NUMBER NOT NULL CONSTRAINT fk_items_order REFERENCES orders (order_id) ON DELETE CASCADE,
  product_id    NUMBER NOT NULL CONSTRAINT fk_items_product REFERENCES products (product_id),
  quantity      NUMBER(6) NOT NULL CONSTRAINT ck_items_qty CHECK (quantity > 0),
  unit_price    NUMBER(10,2) NOT NULL CONSTRAINT ck_items_price CHECK (unit_price >= 0),
  CONSTRAINT uq_items_order_product UNIQUE (order_id, product_id)
);
CREATE INDEX ix_items_product ON order_items (product_id);
COMMENT ON TABLE  order_items IS 'Products in each order (one row per product per order)';
COMMENT ON COLUMN order_items.unit_price IS 'Price at the time of purchase, so later price changes do not alter old orders';

CREATE TABLE payments (
  payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        NUMBER NOT NULL CONSTRAINT uq_payments_order UNIQUE
                  CONSTRAINT fk_payments_order REFERENCES orders (order_id) ON DELETE CASCADE,
  amount          NUMBER(12,2) NOT NULL,
  payment_method  VARCHAR2(30) CONSTRAINT ck_payments_method CHECK (payment_method IN ('CARD', 'UPI', 'NETBANKING')),
  payment_status  VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
                  CONSTRAINT ck_payments_status CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED', 'CANCELLED')),
  transaction_ref VARCHAR2(100) CONSTRAINT uq_payments_txn UNIQUE,
  updated_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE  payments IS 'One payment per order';
COMMENT ON COLUMN payments.amount IS 'Amount to pay = ORDERS.TOTAL_AMOUNT';
COMMENT ON COLUMN payments.payment_status IS 'PENDING -> SUCCESS (or FAILED, retry allowed); REFUNDED / CANCELLED when the order is undone';
COMMENT ON COLUMN payments.transaction_ref IS 'Reference from the payment gateway, e.g. TXN-3F9A1C07B2E4';

CREATE TABLE deliveries (
  delivery_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        NUMBER NOT NULL CONSTRAINT uq_deliveries_order UNIQUE
                  CONSTRAINT fk_deliveries_order REFERENCES orders (order_id) ON DELETE CASCADE,
  delivery_status VARCHAR2(20) DEFAULT 'NOT_SHIPPED' NOT NULL
                  CONSTRAINT ck_deliveries_status CHECK (delivery_status IN
                  ('NOT_SHIPPED', 'PACKED', 'SHIPPED', 'OUT_FOR_DELIVERY', 'DELIVERED', 'RETURNED')),
  courier         VARCHAR2(100),
  tracking_number VARCHAR2(100),
  updated_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE  deliveries IS 'One delivery per order: NOT_SHIPPED -> PACKED -> SHIPPED -> OUT_FOR_DELIVERY -> DELIVERED (or RETURNED)';

-- =====================================================================
-- Audit log: filled automatically by trigger TRG_INVENTORY_AUDIT
-- =====================================================================
CREATE TABLE stock_movements (
  movement_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    NUMBER NOT NULL CONSTRAINT fk_moves_product REFERENCES products (product_id) ON DELETE CASCADE,
  outlet_id     NUMBER NOT NULL CONSTRAINT fk_moves_outlet REFERENCES outlets (outlet_id) ON DELETE CASCADE,
  qty_change    NUMBER(10) NOT NULL,          -- +ve = stock in, -ve = stock out
  movement_type VARCHAR2(20) NOT NULL CONSTRAINT ck_moves_type CHECK (movement_type IN
                ('RESTOCK', 'SALE', 'CANCEL', 'RETURN', 'ADJUSTMENT', 'TRANSFER_IN', 'TRANSFER_OUT', 'MANUAL')),
  note          VARCHAR2(255),
  order_id      NUMBER CONSTRAINT fk_moves_order REFERENCES orders (order_id) ON DELETE SET NULL,
  user_id       NUMBER CONSTRAINT fk_moves_user REFERENCES users (user_id) ON DELETE SET NULL,
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_moves_created ON stock_movements (created_at);
CREATE INDEX ix_moves_product_outlet ON stock_movements (product_id, outlet_id);
CREATE INDEX ix_moves_order ON stock_movements (order_id);
COMMENT ON TABLE  stock_movements IS 'Every stock change ever made, written by trigger TRG_INVENTORY_AUDIT. Never edited';
COMMENT ON COLUMN stock_movements.qty_change IS 'Units added (+) or removed (-)';
COMMENT ON COLUMN stock_movements.movement_type IS 'Why: RESTOCK, SALE, CANCEL, RETURN, ADJUSTMENT, TRANSFER_IN/OUT, MANUAL (plain SQL)';
COMMENT ON COLUMN stock_movements.order_id IS 'Order that caused it (SALE / CANCEL / RETURN)';
COMMENT ON COLUMN stock_movements.user_id IS 'User who made the change; NULL = done automatically';

