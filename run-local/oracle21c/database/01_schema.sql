-- =====================================================================
-- 01_schema.sql  -  Tables, constraints, indexes, column descriptions
--                   and the access-control reference data
-- Run as INVENTORY. Safe to re-run: it drops and recreates every table
-- (this DELETES all data, so run 03_seed_data.sql afterwards).
-- Works on Oracle 19c, 21c, 23ai and 26ai.
--
-- Tables, grouped by purpose:
--   Who can log in, and what they may do (role-based access control)
--     USERS              one row per login account (customers and staff)
--     CUSTOMER_PROFILES  personal details of a customer (1 : 1 with USERS)
--     PROFILES           kinds of user: ADMIN, STORE_MANAGER, WAREHOUSE_STAFF, CUSTOMER
--     PERMISSIONS        single rights, e.g. STOCK_WRITE, REPORT_DOWNLOAD
--     AUTHORIZATIONS     which profile has which permission   (PROFILES  x PERMISSIONS)
--     USER_PROFILES      which user has which profile         (USERS     x PROFILES)
--   Shop
--     OUTLETS, CATEGORIES, SUPPLIERS, PRODUCTS, INVENTORY (stock per product per outlet)
--     ORDERS, ORDER_ITEMS, PAYMENTS, DELIVERIES
--     STOCK_MOVEMENTS    audit log of every stock change (filled by a trigger)
-- Easy-to-read views that join these tables are in 02_inventory_pkg.sql (V_ORDER_DETAILS, V_USER_ACCESS ...).
-- =====================================================================

-- Drop the old tables if they exist (children first). ORA-00942 = "table does not exist", ignored.
BEGIN
  FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list(
              'STOCK_MOVEMENTS', 'DELIVERIES', 'PAYMENTS', 'ORDER_ITEMS', 'ORDERS', 'INVENTORY',
              'PRODUCTS', 'SUPPLIERS', 'CATEGORIES', 'USER_PROFILES', 'AUTHORIZATIONS', 'PERMISSIONS',
              'PROFILES', 'CUSTOMER_PROFILES', 'OUTLETS', 'USERS',
              'APP_USERS'))) LOOP          -- APP_USERS = the users table of the earlier version
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.name || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE <> -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
