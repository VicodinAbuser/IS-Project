    OR (pr.profile_code = 'STORE_MANAGER'   AND pe.permission_code IN
          ('CATALOG_READ', 'CATALOG_WRITE', 'ORDER_READ_ALL', 'ORDER_MANAGE', 'STOCK_READ', 'STOCK_WRITE',
