-- Empty every table and restart the ID numbers at 1.
DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(60);
  v_tables t_list := t_list('stock_movements', 'deliveries', 'payments', 'order_items', 'orders',
                            'inventory', 'products', 'suppliers', 'categories', 'outlets', 'app_users');
  v_ids    t_list := t_list('movement_id', 'delivery_id', 'payment_id', 'order_item_id', 'order_id',
                            'inventory_id', 'product_id', 'supplier_id', 'category_id', 'outlet_id', 'user_id');
BEGIN
  FOR i IN 1 .. v_tables.COUNT LOOP
    EXECUTE IMMEDIATE 'DELETE FROM ' || v_tables(i);
    EXECUTE IMMEDIATE 'ALTER TABLE ' || v_tables(i) || ' MODIFY ' || v_ids(i) ||
                      ' GENERATED BY DEFAULT AS IDENTITY (START WITH 1)';
  END LOOP;
END;
