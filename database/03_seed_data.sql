-- Opening stock + about 260 paid orders spread from 1 January last year until today,
-- so the quarterly reports have data. Stock changes go through INVENTORY_PKG,
-- so the audit trigger records them just like real activity.
DECLARE
  v_admin    NUMBER;
  v_start    TIMESTAMP := CAST(TRUNC(ADD_MONTHS(SYSDATE, -12), 'YYYY') AS TIMESTAMP);
  v_span     NUMBER;
  v_when     TIMESTAMP;
  v_customer NUMBER;
  v_address  app_users.address%TYPE;
  v_outlet   NUMBER;
  v_order    NUMBER;
  v_lines    PLS_INTEGER;
  v_qty      PLS_INTEGER;
  v_total    NUMBER;
  v_delivery VARCHAR2(20);
  TYPE t_names IS TABLE OF VARCHAR2(20);
  v_methods  t_names := t_names('CARD', 'UPI', 'NETBANKING');
  v_transit  t_names := t_names('PACKED', 'SHIPPED', 'OUT_FOR_DELIVERY');
BEGIN
  DBMS_RANDOM.SEED(42);
  SELECT user_id INTO v_admin FROM app_users WHERE email = 'admin@inventory.com';
  v_span := (SYSDATE - CAST(v_start AS DATE)) * 86400;   -- seconds between start and now

  inventory_pkg.set_backdate(v_start);
  FOR p IN (SELECT product_id FROM products ORDER BY product_id) LOOP
    FOR o IN (SELECT outlet_id FROM outlets ORDER BY outlet_id) LOOP
      inventory_pkg.change_stock(p.product_id, o.outlet_id, TRUNC(DBMS_RANDOM.VALUE(60, 161)),
                                 'RESTOCK', v_admin, NULL, 'Opening stock');
    END LOOP;
  END LOOP;

  FOR n IN 1 .. 260 LOOP
    v_when := v_start + NUMTODSINTERVAL(DBMS_RANDOM.VALUE(0, v_span), 'SECOND');
    inventory_pkg.set_backdate(v_when);
    SELECT user_id, address INTO v_customer, v_address FROM (
      SELECT user_id, address FROM app_users WHERE user_role = 'CUSTOMER' ORDER BY DBMS_RANDOM.VALUE
    ) FETCH FIRST 1 ROW ONLY;
    SELECT outlet_id INTO v_outlet FROM (SELECT outlet_id FROM outlets ORDER BY DBMS_RANDOM.VALUE) FETCH FIRST 1 ROW ONLY;

    INSERT INTO orders (customer_id, outlet_id, order_status, shipping_address, created_at)
    VALUES (v_customer, v_outlet, 'PAID', v_address, v_when)
    RETURNING order_id INTO v_order;

    v_total := 0;
    v_lines := TRUNC(DBMS_RANDOM.VALUE(1, 4));
    FOR p IN (SELECT product_id, price FROM (SELECT product_id, price FROM products ORDER BY DBMS_RANDOM.VALUE)
               FETCH FIRST v_lines ROWS ONLY) LOOP
      v_qty := TRUNC(DBMS_RANDOM.VALUE(1, 4));
      IF inventory_pkg.stock_at(p.product_id, v_outlet) - v_qty >= 5 THEN
        inventory_pkg.change_stock(p.product_id, v_outlet, -v_qty, 'SALE', v_customer, v_order, 'Order #' || v_order);
        INSERT INTO order_items (order_id, product_id, quantity, unit_price) VALUES (v_order, p.product_id, v_qty, p.price);
        v_total := v_total + p.price * v_qty;
      END IF;
    END LOOP;

    IF v_total = 0 THEN
      DELETE FROM orders WHERE order_id = v_order;
    ELSE
      UPDATE orders SET total_amount = v_total WHERE order_id = v_order;
      v_delivery := CASE WHEN SYSTIMESTAMP - v_when > INTERVAL '7' DAY THEN 'DELIVERED'
                         ELSE v_transit(TRUNC(DBMS_RANDOM.VALUE(1, 4))) END;
      INSERT INTO payments (order_id, amount, payment_method, payment_status, transaction_ref, updated_at)
      VALUES (v_order, v_total, v_methods(TRUNC(DBMS_RANDOM.VALUE(1, 4))), 'SUCCESS',
              'TXN-' || SUBSTR(RAWTOHEX(SYS_GUID()), 1, 12), v_when);
      INSERT INTO deliveries (order_id, delivery_status, courier, tracking_number, updated_at)
      VALUES (v_order, v_delivery,
              CASE WHEN v_delivery <> 'PACKED' THEN 'BlueDart' END,
              CASE WHEN v_delivery <> 'PACKED' THEN 'BD' || LPAD(v_order, 8, '0') END, v_when);
    END IF;
  END LOOP;

  -- A few items low on stock, so the low-stock alert shows in the demo.
  inventory_pkg.set_backdate(NULL);
  FOR r IN (SELECT i.product_id, i.outlet_id, i.quantity FROM inventory i
              JOIN products p ON p.product_id = i.product_id
              JOIN outlets o ON o.outlet_id = i.outlet_id
             WHERE (p.sku, o.name) IN (('EL-002', 'Mumbai Central'), ('EL-004', 'Bengaluru Store'), ('HK-002', 'Pune Hub'))) LOOP
    inventory_pkg.change_stock(r.product_id, r.outlet_id, 4 - r.quantity, 'ADJUSTMENT', v_admin, NULL, 'Stock audit correction');
  END LOOP;
  COMMIT;
END;
